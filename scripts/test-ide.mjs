import { electronTestOptions } from './electron-test-options.mjs';
import { _electron as electron } from 'playwright-core';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
const build = path.resolve('build/ide-smoke'); await mkdir(build, { recursive: true });
const application = await electron.launch(await electronTestOptions(path.join(build,'profile')));
const errors = [];
try {
  const page = await application.firstWindow(); page.on('pageerror', e => errors.push(e.message));
  page.on('console', e => { if (e.type() === 'error') errors.push(e.text()); });
  await page.waitForSelector('.monaco-editor .view-lines');
  await page.waitForFunction(() => document.querySelector('#tabs').textContent.includes('welcome.slang'));
  await page.locator('#run').click();
  await page.waitForFunction(() => document.querySelector('#console').textContent.includes('Program finished.'));
  assert.match(await page.locator('#console').innerText(), /Hei, verden!/);
  await page.waitForFunction(() => !document.querySelector('#debug').disabled);
  await page.locator('#debug').click();
  await page.waitForFunction(() => !document.querySelector('#step').disabled);
  await page.locator('#step').click();
  await page.waitForFunction(() => document.querySelector('#variables').textContent.includes('verden'));
  await page.locator('#run').click();
  await page.waitForFunction(() => !document.querySelector('#debug').disabled);
  async function replace(source) {
    await page.locator('#editor .view-lines').click(); await page.keyboard.press('ControlOrMeta+a'); await page.keyboard.insertText(source);
  }
  await replace('use graphics as g\ng.');
  await page.keyboard.press('Control+Space');
  await page.waitForSelector('.suggest-widget.visible');
  assert.match(await page.locator('.suggest-widget.visible').innerText(), /background|canvas|circle/);
  await page.keyboard.press('Escape');
  await replace('use strings as s\ns.');
  await page.keyboard.press('Control+Space');
  await page.waitForSelector('.suggest-widget.visible');
  assert.match(await page.locator('.suggest-widget.visible').innerText(), /contains|find|join/);
  await page.keyboard.press('Escape');
  await replace('use numbers as maths\nuse strings as s\nvar øre = 0.01\nprint<s.upper<"blåbær">, maths.sum<list<øre, 0.02>>>');
  await page.locator('#run').click();
  await page.waitForFunction(() => document.querySelector('#console').textContent.includes('Program finished.'));
  assert.match(await page.locator('#console').innerText(), /BLÅBÆR 0.03/);
  await page.waitForFunction(() => !document.querySelector('#debug').disabled);
  await replace('use window as ui\nui.create<"Hello / Hei", 480, 360>\nvar name = ui.input<"Your name / Navnet ditt", "Initial">\nvar message = ui.label<"Ready">\nfunc Greet <>:\nmessage.caption = "Hei, " + name.value\nprint<message.caption>\n.\nui.button<"Greet / Hils", Greet>\nui.run<>');
  await page.locator('#run').click(); await page.waitForSelector('#canvas.visible');
  const form = await page.locator('#canvas').boundingBox();
  await page.locator('#canvas').click({ position: { x: 80 * form.width / 480, y: 110 * form.height / 360 } });
  await page.keyboard.press('ControlOrMeta+a'); await page.keyboard.insertText('Åse Ørn');
  await page.keyboard.press('Tab'); await page.keyboard.press('Enter');
  await page.waitForFunction(() => document.querySelector('#console').textContent.includes('Hei, Åse Ørn'));
  await page.locator('#canvas').screenshot({ path: path.join(build, 'window.png') });
  await page.locator('#close-canvas').click();
  await page.waitForFunction(() => document.querySelector('#console').textContent.includes('Program finished.'));
  await page.waitForFunction(() => !document.querySelector('#debug').disabled);
  await replace('var value =\n');
  await page.waitForFunction(() => document.querySelector('#syntax-status').textContent.includes('syntax error'));
  await replace('print<input<"Your name? ">>\n'); await page.locator('#run').click();
  await page.waitForFunction(() => !document.querySelector('#console-input').disabled);
  await page.locator('#console-input').fill('Ærlig Ørn'); await page.locator('#send-input').click();
  await page.waitForFunction(() => document.querySelector('#console').textContent.includes('Program finished.'));
  assert.match(await page.locator('#console').innerText(), /Ærlig Ørn/);
  await page.waitForFunction(() => !document.querySelector('#debug').disabled);
  await page.locator('#drawing-example').click(); await page.locator('#run').click();
  await page.waitForFunction(() => document.querySelector('#console').textContent.includes('Program finished.'));
  assert.equal(await page.locator('#canvas').evaluate(canvas => canvas.classList.contains('visible')), true);
  assert.deepEqual(await page.locator('#canvas').evaluate(canvas => [...canvas.getContext('2d').getImageData(0,0,1,1).data]), [24,36,58,255]);
  await page.screenshot({ path: path.join(build, 'drawing.png') });
  await page.waitForFunction(() => !document.querySelector('#debug').disabled);
  await page.locator('#tree .tree-row').filter({ hasText: 'graphics' }).click();
  await page.locator('#tree .tree-row').filter({ hasText: 'callback.slang' }).click();
  await page.locator('#run').click(); await page.waitForSelector('#canvas.visible');
  await page.locator('#pause').click(); await page.waitForFunction(() => !document.querySelector('#step').disabled);
  await page.screenshot({ path: path.join(build, 'debug.png') });
  await page.locator('#pause').click(); await page.waitForFunction(() => document.querySelector('#run-state').textContent.includes('Running'));
  await page.locator('#stop').click(); await page.waitForFunction(() => !document.querySelector('#debug').disabled);
  assert.match(await page.locator('#console').innerText(), /Program stopped/);
  await page.locator('#tree .tree-row').filter({ hasText: 'sprite-benchmark.slang' }).click();
  await page.evaluate(() => { window.previewFrames = 0; window.slang.onRunner(e => { if (e.type === 'frame') window.previewFrames++; }); });
  await page.locator('#run').click();
  await page.waitForFunction(() => document.querySelector('#console').textContent.includes('Program finished.'));
  console.log('Embedded sprite benchmark:', (await page.locator('#console').innerText()).trim(), 'Canvas frames:', await page.evaluate(() => window.previewFrames));
  await page.waitForFunction(() => !document.querySelector('#debug').disabled);
  const savePath = path.join(build, 'Ærlig program.slang');
  await application.evaluate(({ dialog }, file) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath: file }); }, savePath);
  await page.locator('#new').click(); await replace('print<"Saved offline">\n'); await page.locator('#save').click();
  await page.waitForFunction(() => document.querySelector('#tabs .selected').textContent.includes('Ærlig program'));
  assert.equal((await readFile(savePath, 'utf8')).replaceAll('\r\n','\n'), 'print<"Saved offline">\n');
  await replace('print<"Changed">\n');
  await application.evaluate(({ dialog }) => { dialog.showMessageBox = async () => ({ response: 2 }); });
  await page.locator('#tabs .selected .close-tab').click();
  assert.match(await page.locator('#tabs .selected').innerText(), /Ærlig program/);
  await application.evaluate(({ dialog }) => { dialog.showMessageBox = async () => ({ response: 0 }); });
  await page.locator('#tabs .selected .close-tab').click();
  await page.waitForFunction(() => !document.querySelector('#tabs .selected').textContent.includes('Ærlig program'));
  assert.equal((await readFile(savePath, 'utf8')).replaceAll('\r\n','\n'), 'print<"Changed">\n');
  const security = await page.evaluate(() => ({ node: typeof window.require, process: typeof window.process, api: Object.keys(window.slang) }));
  assert.equal(security.node, 'undefined'); assert.equal(security.process, 'undefined'); assert.ok(!security.api.includes('send'));
  assert.deepEqual(errors, []);
  console.log('Electron smoke passed: run, debug/step, completion, diagnostics, input, window controls and Unicode editing, SDL canvas, pause/resume/stop, files, save/cancel and renderer isolation.');
} finally {
  await application.evaluate(({ BrowserWindow }) => { for (const window of BrowserWindow.getAllWindows()) window.destroy(); }).catch(() => {});
  await application.close();
}
