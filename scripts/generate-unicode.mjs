// Maintainer-only generation. The generated tables are checked in; users and
// native builds do not require Node. Match the original lexer's Unicode categories.
import { writeFileSync } from 'node:fs';
const ranges = regex => {
  const result = [];
  let first = null;
  for (let cp = 128; cp <= 0x110000; cp++) {
    const matches = cp < 0x110000 && regex.test(String.fromCodePoint(cp));
    if (matches && first === null) first = cp;
    if (!matches && first !== null) { result.push([first, cp - 1]); first = null; }
  }
  return result;
};
let output = `// Generated by scripts/generate-unicode.mjs with Unicode ${process.versions.unicode}.\n`;
for (const [name, regex] of [['letter_ranges', /\p{L}/u], ['continuation_ranges', /[\p{L}\p{M}\p{N}]/u]]) {
  output += `constexpr UnicodeRange ${name}[] = {\n`;
  output += ranges(regex).map(([a, b]) => `    {0x${a.toString(16)}, 0x${b.toString(16)}},`).join('\n');
  output += '\n};\n';
}
writeFileSync(new URL('../native/src/unicode_ranges.inc', import.meta.url), output);
